"""Score and rank companies by combining financial + AI initiative insights.

The module builds a composite prompt that feeds both quantitative
financial data and qualitative AI-initiative text to the LLM, asking
it to assign a 1–100 score per company and produce a ranked list
with justifications.
"""

from __future__ import annotations

import logging

import pandas as pd
from langchain_chroma import Chroma

from duallens_analytics.config import Settings
from duallens_analytics.rag import get_llm

logger = logging.getLogger(__name__)

RANKING_SYSTEM: str = """\
You are a financial and strategic investment assistant.
You will receive two types of information about organisations:

1. **Financial Data** – quantitative performance metrics such as Market Cap, \
   P/E Ratio, Dividend Yield, Beta, and Total Revenue.
2. **AI Initiatives** – qualitative strategic information about AI adoption, \
   innovation, and technology-driven readiness.

Your task:
1. Analyse each organisation across both dimensions.
2. Assign a composite score (1-100) to each organisation based on financial \
   strength *and* AI readiness.
3. Rank the organisations from best to worst investment potential.
4. Provide a clear 2-3 sentence justification for each organisation.

Format your response as a numbered list:
1. TICKER – Score: XX/100
   Justification: …
"""
"""System prompt for the composite ranking evaluator."""

RANKING_USER: str = """\
Using the information below, rank these organisations for investment potential.

### Financial Data
{financial_data}

### AI Initiatives
{ai_initiatives}
"""
"""User-message template with ``{financial_data}`` and ``{ai_initiatives}`` placeholders."""


def rank_companies(
    df: pd.DataFrame,
    vectorstore: Chroma,
    settings: Settings,
) -> str:
    """Prompt the LLM to score and rank companies for investment potential.

    The prompt merges a stringified financial-metrics DataFrame with up
    to 80 AI-initiative document passages retrieved from the vector
    store.

    Args:
        df: Financial-metrics DataFrame (index = ticker symbols).
        vectorstore: ChromaDB store containing AI-initiative documents.
        settings: Application settings forwarded to
            :func:`~duallens_analytics.rag.get_llm`.

    Returns:
        The raw Markdown-formatted ranking text generated by the LLM.
    """
    logger.info("Ranking companies: %s", list(df.index))
    ai_docs = vectorstore.get()["documents"]
    logger.debug("Total AI docs in store: %d (using first 80)", len(ai_docs))
    # Truncate to avoid token limits; take first 80 docs
    ai_text = "\n---\n".join(ai_docs[:80])

    prompt = (
        f"[INST]{RANKING_SYSTEM}\n"
        f"user: {RANKING_USER.format(financial_data=df.to_string(), ai_initiatives=ai_text)}"
        f"[/INST]"
    )
    llm = get_llm(settings)
    logger.debug("Invoking LLM for ranking")
    resp = llm.invoke(prompt)
    logger.info("Ranking response generated (%d chars)", len(resp.content))
    return resp.content
